module.exports = {
  number:    $ => /[0-9]+/,
  boolean:   $ => /[01]+b/,
  byte:      $ => /0x[0-9a-fA-F]+/,
  string:    $ => /"[^"]*"/,
  char:      $ => seq('"', /./, '"'),
  symbol:    $ => /`[A-Za-z0-9._:]*/,
  vector:    $ => prec.left(seq($.number, repeat1(seq($._list_ws, $.number)))),
  null:      $ => '0N',
  infinity:  $ => '0W',
  timestamp: $ => /[0-9]{4}\.[0-9]{2}\.[0-9]{2}D[0-9:.]+/,
  date:      $ => /[0-9]{4}\.[0-9]{2}\.[0-9]{2}/,
  month:     $ => /[0-9]{4}\.[0-9]{2}m/,
  time:      $ => /[0-9]{2}:[0-9]{2}:[0-9]{2}\.[0-9]{3}/,
  minute:    $ => /[0-9]{2}:[0-9]{2}/,
  second:    $ => /[0-9]{2}:[0-9]{2}:[0-9]{2}/,
  timespan:  $ => /[0-9]+D[0-9:.]+/,
  datetime:  $ => /[0-9]{4}\.[0-9]{2}\.[0-9]{2}T[0-9:.]+/,
};
